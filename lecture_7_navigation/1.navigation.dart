// The Navigator is the widget that manages a stack of screens.
//
// Think of screens like cards:
//
// when you open a new screen, Flutter puts a new card on top
// when you go back, Flutter removes the top card
//
// This is called a stack.
//
// What is a Route?
//
// A route is a screen/page in the app.
//
// Examples:
//
// HomePage
// ProfilePage
// DetailsPage
//
// Each screen you navigate to is considered a route.
//
// Main navigation methods
// Navigator.push() → open a new screen
// Navigator.pop() → go back to the previous screen
// Navigator.pushNamed() → open a screen using a route name
// Navigator.popUntil() → go back until a specific route