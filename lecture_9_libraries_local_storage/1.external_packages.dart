// An external package is a library made by other developers that we can add to our Flutter project.

// It gives us ready-made functionality.

// Examples
// http → to call APIs
// shared_preferences → to save small local data
// animated_text_kit → to create text animations
// intl → for date and number formatting
// image_picker → to pick images from the gallery or camera
// Why do we use external packages?

// External packages help us:

// save time
// avoid writing everything manually
// add powerful features quickly
// use community-tested solutions
// Main point

// A package is like a tool we install into our app to give it a new ability.
